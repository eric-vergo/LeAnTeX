// Generates the layout tables of LeAnTeX from KaTeX's own sources: the per-glyph font metrics
// (`fontMetricsData.js`), TeX's font parameters σ and ξ for the three size classes and the
// characters KaTeX measures with the metrics of a look-alike (`fontMetrics.ts`), and the static
// SVG paths (`svgGeometry.ts`). Lengths are written exactly, as integers in units of 1e-5 em
// (KaTeX's tables have at most five decimals); the layout converts them to its fixed point.
//
// Usage (from the repository root; KATEX = a checkout of KaTeX's source at the pinned tag,
// default $KATEX_SOURCE, else .cache/katex-0.19.1):
//   node --experimental-strip-types --no-warnings --import ./tools/ts-register.mjs \
//        tools/gen-layout-tables.mjs [KATEX]
// Re-run after upgrading KaTeX; `git diff` of the output then shows what changed.

import {writeFileSync, readFileSync} from "node:fs";
import {join, resolve} from "node:path";
import {pathToFileURL} from "node:url";

const katexDir = resolve(process.argv[2] ?? process.env.KATEX_SOURCE ?? ".cache/katex-0.19.1");
const src = (p) => pathToFileURL(join(katexDir, "src", p)).href;
const pkg = JSON.parse(readFileSync(join(katexDir, "package.json"), "utf8"));
const KATEX_VERSION = pkg.version;

const metricMap = (await import(src("fontMetricsData.js"))).default;
const {getGlobalMetrics} = await import(src("fontMetrics.ts"));
const {path: svgPaths} = await import(src("svgGeometry.ts"));

const HEADER = "/-\nReleased under Apache 2.0 license as described in the file LICENSE.\n" +
    "Authors: Eric Vergo (Two-Circle Solutions), Claude (Anthropic)\n-/\n";

// A length in em as an exact integer number of 1e-5 em (the tables have at most five decimals).
function decimal5(x) {
    const r = Math.round(Math.abs(x) * 1e5);
    if (Math.abs(r / 1e5 - Math.abs(x)) > 1e-12) throw new Error("more than five decimals: " + x);
    return x < 0 ? -r : r;
}

// A Lean string literal: backslash, quote and newline escaped (the inputs are ASCII paths and
// font names).
function lit(s) {
    return "\"" + s.replace(/\\/g, "\\\\").replace(/"/g, "\\\"").replace(/\n/g, "\\n") + "\"";
}

// Writes a generated Lean module with the header, a module docstring and the body.
function writeLean(rel, title, summary, body) {
    const text = HEADER + "\n/-!\n# " + title + "\n\n" + summary +
        "\nGenerated by `tools/gen-layout-tables.mjs` from KaTeX " + KATEX_VERSION +
        "; do not edit by hand.\n\n## References\n\n" +
        "* KaTeX (MIT licence, see `LICENSE-KaTeX`): <https://github.com/KaTeX/KaTeX>.\n-/\n\n" +
        body;
    writeFileSync(rel, text.replace(/\n+$/, "\n"));
}

// --- glyph metrics -------------------------------------------------------------------------

{
    const fonts = Object.keys(metricMap).sort();
    let body = "namespace LeAnTeX.Data\n\n";
    let glyphs = 0;
    for (const [i, font] of fonts.entries()) {
        const rows = Object.entries(metricMap[font])
            .map(([code, m]) => [Number(code), ...m.map(decimal5)])
            .sort((a, b) => a[0] - b[0]);
        glyphs += rows.length;
        body += `/-- The metrics of \`${font}\`: for each glyph its UTF-16 code unit, depth, ` +
            "height,\nitalic correction, skew and width, in 1e-5 em. -/\n" +
            `def metrics${i} : Array Int := #[\n` +
            rows.map((r) => "  " + r.join(", ")).join(",\n") + "\n]\n\n";
    }
    body += "/-- KaTeX's fonts with their metrics tables (flat, six numbers a glyph). -/\n" +
        "def fontMetricTables : Array (String × Array Int) := #[\n" +
        fonts.map((f, i) => `  (${lit(f)}, metrics${i})`).join(",\n") + "\n]\n\n" +
        "end LeAnTeX.Data\n";
    writeLean("LeAnTeX/Data/FontMetrics.lean", "KaTeX's glyph metrics",
        `The depth, height, italic correction, skew and width of every glyph of KaTeX's ${fonts.length}\n` +
        `fonts (${glyphs} glyphs), from KaTeX's \`fontMetricsData.js\` (which KaTeX derives from ` +
        "the fonts'\nTeX font metric files), keyed by UTF-16 code unit as KaTeX looks them up.\n",
        body);
}

// --- font parameters and look-alike characters ---------------------------------------------

{
    // Size 6 (normal), 3 (script) and 1 (scriptscript) select KaTeX's three size classes.
    const classes = [6, 3, 1].map((s) => getGlobalMetrics(s));
    const keys = Object.keys(classes[0]).filter((k) => k !== "cssEmPerMu");
    const params = keys.map((k) =>
        `  (${lit(k)}, ${classes.map((c) => decimal5(c[k])).join(", ")})`);
    // `extraCharacterMap` is not exported; it is read from the source text.
    const text = readFileSync(join(katexDir, "src", "fontMetrics.ts"), "utf8");
    const block = text.slice(text.indexOf("const extraCharacterMap"));
    const mapText = block.slice(block.indexOf("{") + 1, block.indexOf("};"));
    const extra = [...mapText.matchAll(/'(.)':\s*'(.)'/g)].map((m) =>
        `  (0x${m[1].codePointAt(0).toString(16).toUpperCase()}, ` +
        `0x${m[2].codePointAt(0).toString(16).toUpperCase()})`);
    writeLean("LeAnTeX/Data/FontParams.lean", "KaTeX's font parameters",
        "TeX's font parameters σ and ξ (the `fontdimen`s of `cmsy` and `cmex`) and KaTeX's own " +
        "additions,\nfor text, script and scriptscript size, from `sigmasAndXis` in KaTeX's " +
        "`fontMetrics.ts`; and the\ncharacters KaTeX measures with the metrics of a look-alike " +
        "(`extraCharacterMap`).\n",
        "namespace LeAnTeX.Data\n\n" +
        "/-- Each parameter's value at text, script and scriptscript size, in 1e-5 em. -/\n" +
        "def fontParamList : Array (String × Int × Int × Int) := #[\n" + params.join(",\n") +
        "\n]\n\n" +
        "/-- Characters without metrics of their own and the look-alike whose metrics they " +
        "take. -/\n" +
        "def extraCharacterList : Array (Nat × Nat) := #[\n" + extra.join(",\n") + "\n]\n\n" +
        "end LeAnTeX.Data\n");
}

// --- static SVG paths ----------------------------------------------------------------------

{
    const names = Object.keys(svgPaths).sort();
    // A path is one long literal, cut into pieces of at most 90 columns joined by Lean's string
    // gaps (`\` at a line end; the next line's leading spaces are dropped): a cut never splits
    // an escape and never comes before a space.
    const entry = (name) => {
        const esc = lit(svgPaths[name]).slice(1, -1);
        const pieces = [];
        let i = 0;
        while (i < esc.length) {
            let j = Math.min(esc.length, i + 90);
            while (j < esc.length && j > i + 1 &&
                   (esc[j] === " " || /^(\\\\)*\\$/.test(esc.slice(i, j).match(/\\*$/)[0]))) j--;
            pieces.push(esc.slice(i, j));
            i = j;
        }
        return `  (${lit(name)},\n    "` + pieces.join("\\\n    ") + "\")";
    };
    writeLean("LeAnTeX/Data/SvgPaths.lean", "KaTeX's SVG paths",
        `The ${names.length} fixed SVG paths of KaTeX's \`svgGeometry.ts\` (stretchy arrows, braces, ` +
        "the vector\naccent, …), in KaTeX's viewBox units (1000 a em).\n",
        "namespace LeAnTeX.Data\n\n" +
        "/-- KaTeX's named SVG paths. -/\n" +
        "def svgPathList : Array (String × String) := #[\n" + names.map(entry).join(",\n") +
        "\n]\n\nend LeAnTeX.Data\n");
}

console.log(`KaTeX ${KATEX_VERSION}: layout tables written`);
