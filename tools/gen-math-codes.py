# Writes LeAnTeX/TeXMath/Data/MathCodes.lean from fixtures/math-codes/codes.tsv (recorded by
# tools/math-codes.sh from LuaLaTeX): the math characters (class, family, slot) of LaTeX's
# symbols, its delimiters (small and large variants), its math accents (family and slot) and
# the \mathcode and \delcode of the ASCII characters, as the TeX-rule math layout looks them up.
# Why a generator: the table is data recorded from TeX, regenerated when the recording changes.
#
# Usage, from the repository root:  python3 -I tools/gen-math-codes.py

import re

HEADER = '''/-
Released under Apache 2.0 license as described in the file LICENSE.
Authors: Eric Vergo (Two-Circle Solutions), Claude (Anthropic)
-/

/-!
# LaTeX's math codes

How LaTeX, with amsmath and amssymb and the document fonts of the reference setup, defines its
math symbols, as recorded from LuaLaTeX by `tools/math-codes.sh`
(`fixtures/math-codes/codes.tsv`): each symbol's class, family and slot, each delimiter's small
and large variants, each math accent's family and slot, and the ASCII characters' `\\mathcode`
and `\\delcode`. Generated by `tools/gen-math-codes.py`; do not edit by hand.

Families as LuaLaTeX numbers them in this setup: 0 operators (the text font), 1 letters
(`cmmi`), 2 symbols (`cmsy`), 3 large symbols (`cmex`), 4 `AMSa` (`msam`), 5 `AMSb` (`msbm`),
6 the legacy operators (`cmr`).
-/

namespace LeAnTeX.TeXMath.Data
'''


def lean_str(s):
    """A Lean string literal of s."""
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    """Reads the recording and writes the Lean table."""
    chars, delims, accents, mcodes, dcodes = {}, {}, {}, {}, {}
    with open('fixtures/math-codes/codes.tsv', encoding='utf-8') as f:
        for line in f:
            row = line.rstrip('\n').split('\t')
            if len(row) < 3:
                continue
            name, kind, _note, fields = row[0], row[1], row[2], row[3:]
            if kind == 'mathchar' and len(fields) == 3:
                chars.setdefault(name, tuple(int(x) for x in fields))
            elif kind == 'delimiter' and len(fields) == 5:
                delims.setdefault(name, tuple(int(x) for x in fields))
            elif kind == 'mathcode' and len(fields) == 3:
                mcodes[name] = tuple(int(x) for x in fields)
            elif kind == 'delcode' and len(fields) == 4:
                dcodes[name] = tuple(int(x) for x in fields)
            elif kind == 'macro' and fields:
                m = re.search(r'\\mathaccentV \{\w+\}([0-9A-F])([0-9A-F]{2})', fields[0])
                if m:
                    accents.setdefault(name, (int(m.group(1), 16), int(m.group(2), 16)))
    out = [HEADER]
    out.append('/-- Math characters: name, class, family, slot. -/')
    out.append('def mathChars : Array (String × Nat × Nat × Nat) := #[')
    out += [f'  ({lean_str(n)}, {c}, {fa}, {s}),' for n, (c, fa, s) in sorted(chars.items())]
    out.append(']\n')
    out.append('/-- Delimiters: name, class, small family and slot, large family and slot. -/')
    out.append('def delimiters : Array (String × Nat × Nat × Nat × Nat × Nat) := #[')
    out += [f'  ({lean_str(n)}, {c}, {a}, {b}, {d}, {e}),'
            for n, (c, a, b, d, e) in sorted(delims.items())]
    out.append(']\n')
    out.append('/-- Math accents: name, family, slot. -/')
    out.append('def accents : Array (String × Nat × Nat) := #[')
    out += [f'  ({lean_str(n)}, {fa}, {s}),' for n, (fa, s) in sorted(accents.items())]
    out.append(']\n')
    out.append('/-- The `\\mathcode` of ASCII characters: character, class (8 for an active')
    out.append('character), family, slot. -/')
    out.append('def mathCodes : Array (Char × Nat × Nat × Nat) := #[')
    out += [f"  ({lean_str(n).replace(chr(34), chr(39), 1)[:-1]}', {c}, {fa}, {s}),"
            for n, (c, fa, s) in sorted(mcodes.items()) if len(n) == 1 and n not in "'\\"]
    out += [f"  ('\\{n}', {c}, {fa}, {s})," for n, (c, fa, s) in sorted(mcodes.items())
            if n in "'\\"]
    out.append(']\n')
    out.append('/-- The `\\delcode` of ASCII characters that have one: character, small family')
    out.append('and slot, large family and slot. -/')
    out.append('def delCodes : Array (Char × Nat × Nat × Nat × Nat) := #[')
    for n, (a, b, d, e) in sorted(dcodes.items()):
        ch = "'\\\\'" if n == '\\' else ("'\\''" if n == "'" else f"'{n}'")
        out.append(f'  ({ch}, {a}, {b}, {d}, {e}),')
    out.append(']\n')
    out.append('end LeAnTeX.TeXMath.Data')
    with open('LeAnTeX/TeXMath/Data/MathCodes.lean', 'w', encoding='utf-8') as f:
        f.write('\n'.join(out) + '\n')


main()
